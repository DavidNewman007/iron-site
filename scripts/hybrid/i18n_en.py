_СЛОВО = re.compile(r"[а-яА-ЯёЁ][а-яА-ЯёЁ-]*")
_КИРИЛЛИЦА = re.compile(r"[а-яА-ЯёЁ]")


def _применить_фразы(text: str) -> str:
    # Регистр не учитываем, но сохраняем: каталог пишет одну и ту же
    # формулировку по-разному («Детектор ДТП» в начале перечня и «детектор
    # ДТП» в середине), а заводить обе строчки в словарь — лишний труд.
    for ru in sorted(PHRASES, key=len, reverse=True):
        en = PHRASES[ru]

        def _замена(m: re.Match[str], en: str = en) -> str:
            найдено = m.group(0)
            return en[0].upper() + en[1:] if найдено[0].isupper() else en

        text = re.sub(re.escape(ru), _замена, text, flags=re.IGNORECASE)
    return text


def _применить_единицы(text: str) -> str:
    for шаблон, en in UNITS:
        text = re.sub(шаблон, en, text)
    return text


def spec_key(key: str) -> str:
    """Название характеристики. Незнакомое — остаётся русским."""
    return SPEC_KEYS.get(key.strip(), key)


def spec_value(value: str) -> str:
    """Значение характеристики. Правило «всё или ничего» — см. модульный докстринг."""
    text = str(value or "")
    if not _КИРИЛЛИЦА.search(text):
        return text

    out = _применить_единицы(_применить_фразы(text))
    if not _КИРИЛЛИЦА.search(out):
        return re.sub(r"\s{2,}", " ", out).strip()

    неизвестное = False

    def замена(m: re.Match[str]) -> str:
        nonlocal неизвестное
        слово = m.group(0)
        en = WORDS.get(слово.lower())
        if not en and "-" in слово:
            # Составное через дефис переводим по частям: «фен-стайлер» →
            # «hair styler», «фитнес-браслет» → «fitness band». Держать такие
            # пары в словаре целиком бессмысленно — поставщик собирает их из тех
            # же слов бесконечными сочетаниями (28.08.2026).
            части = [WORDS.get(ч.lower()) for ч in слово.split("-") if ч]
            if части and all(части):
                en = " ".join(части)
        if not en:
            неизвестное = True
            return слово
        return en[0].upper() + en[1:] if слово[0].isupper() else en

    out = _СЛОВО.sub(замена, out)
    if неизвестное:
        return text
    return re.sub(r"\s{2,}", " ", out).strip()


_ТОВАРНЫЙ_СЛОВАРЬ: dict[str, dict[str, str]] | None = None


def _товарный_словарь() -> dict[str, dict[str, str]]:
    """Словарь названий товаров — ТОТ ЖЕ, что у магазина.

    Названия переводит `public/js/i18n.js` (productName) по
    `public/data/i18n/shop.en.json`, и заводить для карточек вторую копию значило
    бы развести их: магазин показывал бы «Protective glass», а карточка того же
    товара — «Защитное стекло». Так и было до 28.08.2026 — карточка вообще не
    переводила название.
    """
    global _ТОВАРНЫЙ_СЛОВАРЬ
    if _ТОВАРНЫЙ_СЛОВАРЬ is None:
        путь = Path(__file__).resolve().parents[2] / "public" / "data" / "i18n" / "shop.en.json"
        данные = json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else {}
        _ТОВАРНЫЙ_СЛОВАРЬ = {
            "words": {k: v for k, v in (данные.get("product_words") or {}).items() if not k.startswith("_")},
            "phrases": {k: v for k, v in (данные.get("product_phrases") or {}).items() if not k.startswith("_")},
        }
    return _ТОВАРНЫЙ_СЛОВАРЬ


def product_name(name: str) -> str:
    """Название товара по-английски. Порядок слоёв и правило «всё или ничего» —
    как в `i18n.js`: не знаем хотя бы одного слова — отдаём исходную строку
    целиком, потому что наполовину переведённое название читается хуже русского.
    """
    text = str(name or "")
    if not _КИРИЛЛИЦА.search(text):
        return text
    словарь = _товарный_словарь()
    out = text
    for фраза in sorted(словарь["phrases"], key=len, reverse=True):
        out = re.sub(re.escape(фраза), словарь["phrases"][фраза], out, flags=re.I)
    out = re.sub(r"(\d+)\s*шт\.?", r"\1 pcs", out, flags=re.I)
    if not _КИРИЛЛИЦА.search(out):
        return re.sub(r"\s{2,}", " ", out).strip()

    неизвестное = False

    def замена(m: re.Match[str]) -> str:
        nonlocal неизвестное
        слово = m.group(0)
        en = словарь["words"].get(слово.lower())
        if not en:
            неизвестное = True
            return слово
        return en[0].upper() + en[1:] if слово[0].isupper() else en

    out = _СЛОВО.sub(замена, out)
    if неизвестное:
        return text
    return re.sub(r"\s{2,}", " ", out).strip()


def translate_specs(specs: list[dict]) -> list[dict]:
    return [{"key": spec_key(s["key"]), "value": spec_value(s["value"])} for s in specs]
