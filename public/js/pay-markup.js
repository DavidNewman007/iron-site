/**
 * Наценка онлайн-оплаты: налог и комиссия эквайринга обратным процентом.
 * Заведено 14.09.2026 (план 70).
 *
 * Зачем обратный процент, а не «прибавить 7,7% к цене». Цена товара в прайсе —
 * то, что владелец должен получить ЧИСТЫМИ. Налог и комиссия берутся не с цены
 * товара, а с суммы, которая реально пришла на счёт. Прибавь мы проценты к цене
 * напрямую — с выросшей суммы и налог вырос бы, и часть маржи всё равно ушла.
 * Поэтому итог = цена / (1 − налог − комиссия): после всех удержаний из итога
 * остаётся ровно цена из прайса.
 *
 * Ставки лежат в /data/pay-rates.json — один файл на сайт и на облачную функцию,
 * которая создаёт платёж. Здесь их дублировать нельзя: витрина и касса разъедутся.
 */
(function () {
  "use strict";

  var URL_СТАВОК = "/data/pay-rates.json";
  var кэш = null;

  // Запасные ставки на случай, если файл не отдался. Специально ЗАВЫШЕНЫ (карта
  // по полной ставке 2,5%): лучше показать клиенту сумму чуть больше нужной, чем
  // продать в минус. Расхождение с боевым расчётом функции здесь не страшно —
  // окончательную сумму всё равно считает она, а не браузер.
  var ЗАПАСНЫЕ = {
    налог: 0.07,
    комиссия: { сбп: 0.007, карта: 0.025, карта_льгота_до: "1970-01-01", карта_после: 0.025 },
    округление: { шаг: 50, порог: 1000 },
  };

  function load() {
    if (кэш) return Promise.resolve(кэш);
    return fetch(URL_СТАВОК, { cache: "no-store" })
      .then(function (r) {
        if (!r.ok) throw new Error("pay-rates " + r.status);
        return r.json();
      })
      .then(function (д) {
        кэш = д;
        return д;
      })
      .catch(function (e) {
        console.warn("[pay-markup] ставки не загрузились, беру запасные:", e);
        кэш = ЗАПАСНЫЕ;
        return кэш;
      });
  }

  /** Ставка комиссии банка для способа оплаты на дату. */
  function ставка(rates, способ, дата) {
    var k = (rates && rates.комиссия) || {};
    if (способ === "сбп") return Number(k.сбп) || 0;
    var сегодня = (дата || new Date()).toISOString().slice(0, 10);
    var льгота = String(k.карта_льгота_до || "");
    // Льготный тариф действует ПО указанную дату включительно; дальше ставка
    // переключается сама, без правки кода и без участия человека.
    if (льгота && сегодня <= льгота) return Number(k.карта) || 0;
    return Number(k.карта_после) || Number(k.карта) || 0;
  }

  /** Округление вверх: до шага (50 ₽) для крупных сумм, до рубля для мелких. */
  function округлить(сумма, rates) {
    var о = (rates && rates.округление) || {};
    var шаг = Number(о.шаг) || 1;
    var порог = Number(о.порог) || 0;
    if (сумма < порог || шаг <= 1) return Math.ceil(сумма);
    return Math.ceil(сумма / шаг) * шаг;
  }

  /** Итоговая сумма к оплате для способа: цена / (1 − налог − комиссия). */
  function gross(netto, способ, rates, дата) {
    var цена = Number(netto) || 0;
    if (цена <= 0) return 0;
    var доля = 1 - (Number(rates && rates.налог) || 0) - ставка(rates, способ, дата);
    // Сумма ставок 100% и больше — ошибка в файле ставок, а не бизнес-случай.
    // Проверка ловит и NaN: NaN > 0 всегда false. Вернуть цену без наценки
    // безопаснее, чем делить на ноль и показать клиенту Infinity.
    if (!(доля > 0)) {
      console.warn("[pay-markup] сумма ставок ≥ 100%, наценка не применена");
      return округлить(цена, rates);
    }
    return округлить(цена / доля, rates);
  }

  /** Разбивка для корзины: сколько стоят товары и сколько прибавила оплата. */
  function breakdown(netto, rates, дата) {
    var цена = Number(netto) || 0;
    var out = { товары: цена, способы: {} };
    ["сбп", "карта"].forEach(function (способ) {
      var итог = gross(цена, способ, rates, дата);
      out.способы[способ] = {
        итог: итог,
        наценка: Math.max(0, итог - цена),
        ставка: ставка(rates, способ, дата),
      };
    });
    return out;
  }

  function формат(n) {
    return (Number(n) || 0).toLocaleString("ru-RU") + " ₽";
  }

  window.IRON_PAY = {
    load: load,
    ставка: ставка,
    gross: gross,
    breakdown: breakdown,
    округлить: округлить,
    формат: формат,
    ЗАПАСНЫЕ: ЗАПАСНЫЕ,
  };
})();
